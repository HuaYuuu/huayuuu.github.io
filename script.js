const renderTags = (tags) => tags.map((tag) => `<span class="tag">${tag}</span>`).join("");
const renderLines = (lines) => lines.map((line) => `<span>${line}</span>`).join("");

const publicationList = document.querySelector("[data-publication-list]");
const renderPublications = (filter = "all") => {
  const publications = profileData.publications.filter((paper) => filter === "all" || paper.tags.includes(filter));
  publicationList.innerHTML = publications
    .map(
      (paper) => `
        <article class="publication-card">
          <div class="paper-meta">
            <span class="paper-year">${paper.year}</span>
            ${paper.citations ? `<span class="paper-citations">${paper.citations} citations</span>` : ""}
          </div>
          <div class="paper-main">
            <h3>${paper.title}</h3>
            <p class="paper-authors">${paper.authors}</p>
            <p class="paper-venue-line">${paper.venue}</p>
            <div class="paper-links">
              ${paper.links.map((link) => `<a href="${link.url}">${link.label}</a>`).join("")}
            </div>
            <div class="tag-list">${renderTags(paper.tags)}</div>
          </div>
          <img class="paper-figure" src="${paper.image}" alt="Representative figure for ${paper.title}" />
        </article>
      `
    )
    .join("");
};

renderPublications();

document.querySelectorAll("[data-filter]").forEach((button) => {
  button.addEventListener("click", () => {
    document.querySelectorAll("[data-filter]").forEach((item) => item.classList.remove("active"));
    button.classList.add("active");
    renderPublications(button.dataset.filter);
  });
});

